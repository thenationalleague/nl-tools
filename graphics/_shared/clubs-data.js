/* Crest URL — exact club name, URL-encoded, from the repo */
window.NL_CREST_BASE = "/assets/crests/";
window.crestUrl = function (name) {
  if (!name) return null;
  return encodeURI(window.NL_CREST_BASE + name + ".png");
};

/* Lookup helpers */
window.NL_CLUB_BY_NAME = {};
function nlRebuildLookup() {
  window.NL_CLUB_BY_NAME = {};
  window.NL_CLUBS.forEach(function (c) { window.NL_CLUB_BY_NAME[c.name.toLowerCase()] = c; });
}
nlRebuildLookup();
window.clubByName = function (name) {
  if (!name) return null;
  return window.NL_CLUB_BY_NAME[String(name).trim().toLowerCase()] || null;
};

/* ------------------------------------------------------------------
   Live source of truth: fetch clubs-meta.json from the repo at load.
   The baked list above is only an offline fallback. On success we
   replace NL_CLUBS and fire "nl-clubs-updated" so the tools refresh
   their team list + re-render with the current clubs / short names.
   ------------------------------------------------------------------ */
window.NL_META_URL = "/assets/data/clubs-meta.json";
(function () {
  /* division for the current season = the highest season key in the club's
     seasons map (auto-advances as new seasons are added), else `division` */
  function currentDivision(club) {
    var s = club.seasons || {};
    var years = Object.keys(s).map(Number).filter(function (n) { return !isNaN(n); });
    if (years.length) { var mx = Math.max.apply(null, years); return s[String(mx)] || club.division; }
    return club.division;
  }
  try {
    fetch(window.NL_META_URL, { cache: "no-store" })
      .then(function (r) { if (!r.ok) throw new Error("meta " + r.status); return r.json(); })
      .then(function (j) {
        var clubs = (j && j.clubs) || j;
        if (!Array.isArray(clubs) || !clubs.length) return;
        window.NL_CLUBS = clubs.map(function (c) {
          return {
            name: c.name,
            division: currentDivision(c),
            primary: (c.colors && c.colors.primary) || "#444444",
            short: c.short || c.name
          };
        }).sort(function (a, b) { return a.name.localeCompare(b.name); });
        nlRebuildLookup();
        window.NL_CLUBS_LIVE = true;
        try { window.dispatchEvent(new CustomEvent("nl-clubs-updated")); } catch (e) {}
      })
      .catch(function () { /* keep baked fallback */ });
  } catch (e) { /* keep baked fallback */ }
})();
