/* The Wellbeing Hub's generated HTML must match its source.

   /wellbeing-hub/index.html and poster.html are GENERATED by
   scripts/build-wellbeing-hub.py and also COMMITTED, because the site is
   served straight from the repo with no build step. That combination has two
   bad failure modes, neither visible in a diff review:

     - Somebody edits index.html by hand. It works, ships, and is silently
       reverted by the next generator run.
     - Somebody edits the generator and forgets to commit the output. The
       source and the artefact disagree, and the live page is the old one.

   So CI regenerates and compares. This is also the mechanism behind the
   promise that the National League and Trident editions stay in step: they
   come out of one content file, and this test fails if either committed copy
   has drifted from it.

   The generator lived in a session scratchpad until 13/10/2026 and was one
   container restart from being lost. This test is half of why it can be
   trusted now; the other half is that it is in the repo at all.

   Run with `npm test`. Needs python3, which CI has — it already runs
   scripts/check-workflows.py and the board-exposure unittest suite. */

import test from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { join } from 'node:path';
import { REPO } from './load-canon.mjs';

const SCRIPT = 'scripts/build-wellbeing-hub.py';

test('the generator and its content are in the repo, not a temp directory', () => {
  /* The point of the move. If either of these is missing, the hub has no
     source again and everything below is meaningless. */
  for (const f of [SCRIPT, 'wellbeing-hub/_src/content.json']) {
    assert.ok(existsSync(join(REPO, f)), `${f} is missing`);
  }
});

test('the committed HTML matches what the generator produces', () => {
  const r = spawnSync('python3', ['-I', SCRIPT, '--check'], {
    cwd: REPO, encoding: 'utf8',
  });
  assert.equal(
    r.status, 0,
    'wellbeing-hub output has drifted from its source.\n' +
    'Run: python3 scripts/build-wellbeing-hub.py — then commit the result.\n\n' +
    (r.stderr || '') + (r.stdout || '')
  );
});

test('--check writes nothing', () => {
  /* A check that repairs the thing it is checking would always pass, and
     would quietly rewrite a working tree in CI. */
  const before = spawnSync('git', ['status', '--porcelain', 'wellbeing-hub'],
    { cwd: REPO, encoding: 'utf8' }).stdout;
  spawnSync('python3', ['-I', SCRIPT, '--check'], { cwd: REPO, encoding: 'utf8' });
  const after = spawnSync('git', ['status', '--porcelain', 'wellbeing-hub'],
    { cwd: REPO, encoding: 'utf8' }).stdout;
  assert.equal(after, before, '--check modified the working tree');
});

test('no absolute path from the machine it was written on', () => {
  /* It carried /tmp/claude-0/... and /home/user/tools/... while it lived in a
     scratchpad. Either one makes the generator unrunnable for anybody else,
     which is a silent failure: the file is present, so it looks maintained. */
  const r = spawnSync('git', ['show', `HEAD:${SCRIPT}`], { cwd: REPO, encoding: 'utf8' });
  const src = r.status === 0 ? r.stdout : '';
  const live = spawnSync('cat', [SCRIPT], { cwd: REPO, encoding: 'utf8' }).stdout;
  for (const [what, text] of [['working copy', live], ['HEAD', src]]) {
    if (!text) continue;
    const body = text.replace(/"""[\s\S]*?"""/g, '').replace(/^\s*#.*$/gm, '');
    for (const bad of ['/tmp/claude-', '/home/user/']) {
      assert.ok(!body.includes(bad), `${what} of ${SCRIPT} hardcodes ${bad}`);
    }
  }
});
